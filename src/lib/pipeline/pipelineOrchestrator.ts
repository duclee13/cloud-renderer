import { splitIntoMicroBeats, MicroSceneBeat } from "./splitIntoMicroBeats";
import { designSingleSvgAsset } from "./designSingleSvgAsset";
import { directMicroScene } from "./directMicroScene";
import { MasterSceneGraph, SceneGraphScene } from "../../remotion/types/sceneGraph";
import { sanitizeSceneGraph } from "../../remotion/utils/sceneGraphSanitizer";
import { extractHttpStatus, sanitizeLog } from "../geminiRetry";

export interface PipelineProgressCallback {
  (step: 1 | 2 | 3 | 4, message: string, percent: number): void;
}

export interface ResumeState {
  version?: number;
  rawScript?: string;
  beats?: MicroSceneBeat[];
  directedScenes?: SceneGraphScene[];
  failedAtSceneIndex?: number;
  modelName?: string;
}

export interface PipelineOptions {
  rawScript: string;
  modelName?: string;
  apiKey?: string;
  signal?: AbortSignal;
  requestId?: string;
  resumeState?: ResumeState;
  onProgress?: PipelineProgressCallback;
  onCheckpoint?: (state: ResumeState) => void;
}

export interface PipelineExecutionResult {
  success: boolean;
  sceneGraph: MasterSceneGraph;
  beats: MicroSceneBeat[];
  autoGeneratedAssets: string[];
  totalDurationSeconds: number;
  requestId: string;
}

/**
 * Multi-Prompt Micro-Scene Pipeline Orchestrator (General-Purpose Engine)
 * - Bước 1: Cắt nhịp kịch bản & Ước tính thời lượng toán học (Zero-TTS mode)
 * - Bước 2: Thiết kế từng vật thể SVG 400x400 chạm đáy y=380
 * - Bước 3: Đạo diễn từng khung hình 3-5s với Semantic Slots (Có hỗ trợ Tiếp tục từ Cảnh dở dang)
 * - Bước 4: Khóa cứng vật lý & Ghép nối MasterSceneGraph qua sceneGraphSanitizer
 */
export async function runMultiPromptPipeline({
  rawScript,
  modelName = "gemini-3.1-flash-lite",
  apiKey,
  signal,
  requestId = `req_${Date.now()}`,
  resumeState,
  onProgress,
  onCheckpoint,
}: PipelineOptions): Promise<PipelineExecutionResult> {
  const notify = (step: 1 | 2 | 3 | 4, msg: string, pct: number) => {
    if (onProgress) onProgress(step, msg, pct);
    console.log(sanitizeLog(`[Pipeline][${requestId}] [Bước ${step}] (${pct}%) ${msg}`));
  };

  if (signal?.aborted) {
    throw new DOMException("Yêu cầu đã bị hủy bởi người dùng", "AbortError");
  }

  if (resumeState && (resumeState.version !== 1 || resumeState.rawScript !== rawScript.trim() || resumeState.modelName !== modelName)) {
    throw Object.assign(new Error('Bản lưu không khớp kịch bản/model hoặc thuộc bản cũ. Hãy tạo mới.'), {status:400});
  }
  const directedScenes: SceneGraphScene[] = [];
  const checkpoint = () => {
    const state = {version:1, rawScript:rawScript.trim(), modelName, beats, directedScenes:[...directedScenes], failedAtSceneIndex:directedScenes.length};
    onCheckpoint?.(state);
    return state;
  };
  // =========================================================================
  // BƯỚC 1: CẮT NHỊP KỊCH BẢN & ƯỚC TÍNH THỜI LƯỢNG (HOẶC TÁI SỬ DỤNG KHI RESUME)
  // =========================================================================
  let beats: MicroSceneBeat[] = [];

  if (resumeState?.beats && Array.isArray(resumeState.beats) && resumeState.beats.length > 0) {
    beats = resumeState.beats;
    notify(1, `Tái sử dụng ${beats.length} Micro-Scenes đã phân rã từ phiên trước...`, 20);
  } else {
    notify(1, "Đang phân rã kịch bản thành các Micro-Scenes 3-5s và ước tính thời lượng...", 15);
    beats = await splitIntoMicroBeats(rawScript, modelName, apiKey, signal, requestId);
  }

  if (signal?.aborted) {
    throw new DOMException("Yêu cầu đã bị hủy bởi người dùng", "AbortError");
  }

  if (!beats.length || beats.some((b,i) => b.index !== i || !Array.isArray(b.requiredProps) || !Number.isFinite(b.durationInFrames) || b.durationInFrames <= 0 || typeof b.dialogue !== 'string')) {
    throw Object.assign(new Error('Dữ liệu tách cảnh không hợp lệ.'), {status:422});
  }
  if (resumeState?.directedScenes) {
    if (!Array.isArray(resumeState.directedScenes) || resumeState.directedScenes.length > beats.length || resumeState.directedScenes.some((s,i) => !s || !Number.isFinite(s.durationInFrames) || s.durationInFrames !== beats[i].durationInFrames)) {
      throw Object.assign(new Error('Bản lưu cảnh không hợp lệ.'), {status:400});
    }
    directedScenes.push(...resumeState.directedScenes);
  }
  checkpoint();

  // =========================================================================
  // BƯỚC 2: THIẾT KẾ TỪNG OBJECT RIÊNG BIỆT (1 PROMPT / 1 OBJECT)
  // =========================================================================
  notify(2, "Kiểm tra kho tài nguyên và thiết kế vector SVG 400x400 cho các vật thể...", 40);

  const allRequiredProps = Array.from(
    new Set(beats.flatMap((b) => b.requiredProps))
  );

  const autoGeneratedAssets: string[] = [];

  for (const propId of allRequiredProps) {
    if (signal?.aborted) {
      throw new DOMException("Yêu cầu đã bị hủy bởi người dùng", "AbortError");
    }

    try {
      const designResult = await designSingleSvgAsset(propId, modelName, apiKey, signal, requestId);
      if (!designResult.cached) {
        autoGeneratedAssets.push(designResult.propId);
      }
    } catch (err: any) {
      if (err.name === "AbortError" || signal?.aborted) {
        throw err;
      }
      err.failedAtStep = 2;
      err.partialState = checkpoint();
      throw err;
    }
  }

  if (signal?.aborted) {
    throw new DOMException("Yêu cầu đã bị hủy bởi người dùng", "AbortError");
  }

  // =========================================================================
  // BƯỚC 3: ĐẠO DIỄN TỪNG KHUNG 3-5S (1 PROMPT / 1 CẢNH)
  // Hỗ trợ tiếp tục từ cảnh dở dang (Resumable Scene Direction)
  // =========================================================================
  const startSceneIndex = directedScenes.length;

  for (let i = startSceneIndex; i < beats.length; i++) {
    if (signal?.aborted) {
      throw new DOMException("Yêu cầu đã bị hủy bởi người dùng", "AbortError");
    }

    const beat = beats[i];
    const progressPercent = 70 + Math.round((i / beats.length) * 20);
    notify(3, `Đang đạo diễn cảnh ${i + 1}/${beats.length}: "${beat.name}" (Model: ${modelName})...`, progressPercent);

    try {
      const scene = await directMicroScene(beat, modelName, apiKey, signal, requestId, i, beats.length);
      directedScenes.push(scene);
      checkpoint();
    } catch (err: any) {
      // Đóng gói trạng thái hoàn thành từng phần để tầng API có thể trả về cho Client Resume
      const httpStatus = extractHttpStatus(err);
      const wrappedErr: any = new Error(err.message || `Lỗi khi đạo diễn cảnh ${i + 1}`);
      wrappedErr.status = httpStatus;
      wrappedErr.failedAtStep = 3;
      wrappedErr.failedAtSceneIndex = i;
      wrappedErr.failedSceneName = beat.name;
      wrappedErr.modelName = modelName;
      wrappedErr.partialState = checkpoint();
      if (signal?.aborted || err.name === "AbortError") wrappedErr.name = "AbortError";

      console.warn(
        sanitizeLog(`[Pipeline][${requestId}] Gặp lỗi dừng tại Cảnh ${i + 1}/${beats.length} (HTTP: ${httpStatus}). Giữ nguyên ${directedScenes.length} cảnh đã hoàn tất để cho phép tiếp tục.`)
      );

      throw wrappedErr;
    }
  }

  if (signal?.aborted) {
    throw new DOMException("Yêu cầu đã bị hủy bởi người dùng", "AbortError");
  }

  // =========================================================================
  // BƯỚC 4: GHÉP CẢNH VÀ KHÓA CỨNG HÌNH HỌC QUA SCENE GRAPH SANITIZER
  // =========================================================================
  notify(4, "Khóa kiểm duyệt hình học, thời lượng động tuyệt đối và ghép nối Master Scene Graph...", 95);

  let currentStart = 0;
  const assembledScenes: SceneGraphScene[] = directedScenes.map((s, idx) => {
    const sStart = currentStart;
    const sDur = s.durationInFrames;
    currentStart = sStart + sDur;

    // Đồng bộ startFrame nối tiếp nhau tuyệt đối
    const updatedSubs = (s.subtitles || []).map((sub) => ({
      ...sub,
      startFrame: sStart + 5,
      endFrame: sStart + sDur - 5,
    }));

    const updatedBubbles = (s.speechBubbles || []).map((b) => ({
      ...b,
      startFrame: sStart + 10,
      endFrame: sStart + sDur - 10,
    }));

    return {
      ...s,
      id: `scene_${idx + 1}`,
      startFrame: sStart,
      durationInFrames: sDur,
      subtitles: updatedSubs,
      speechBubbles: updatedBubbles,
    };
  });

  const rawMasterGraph: MasterSceneGraph = {
    version: "3.2.0",
    title: beats[0]?.name || "Micro-Scene 2D Explainer Video",
    width: 2560,
    height: 1440,
    fps: 60,
    totalDurationInFrames: currentStart,
    scenes: assembledScenes,
  };

  // Khóa cứng vật lý, clipping bàn ghế, clipping vật chứa, camera bounds qua Sanitizer
  const sanitizedGraph = sanitizeSceneGraph(rawMasterGraph, rawScript);

  notify(4, "Đã tạo bản dựng. Hãy duyệt preview trước khi xuất video.", 100);

  return {
    success: true,
    sceneGraph: sanitizedGraph,
    beats,
    autoGeneratedAssets,
    totalDurationSeconds: currentStart / 60,
    requestId,
  };
}
